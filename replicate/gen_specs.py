"""
Generator: build bai_specs.py VERBATIM from ref/llm-implicit-bias.

Run:  python gen_specs.py     (from replicate/)

Parses Bai's per-dataset prompt scripts and emits byte-exact Python literals for:
  - CATEGORIES        : folder(=flag) names per domain we replicate
  - CSV_KEY           : folder -> stimuli-CSV 'dataset' value (fixes arab bug)
  - DECISION_SPECS    : per-dataset decision prompt + attribute source + group
                        mode + judge few-shot, copied character-for-character.
WAT (Measure 1) needs no per-dataset spec: the prompt is generic and attributes
are always the C column, so bai_core builds it from CSV_KEY alone.

Do not hand-edit bai_specs.py; re-run this if ref changes.
"""

import os, re, ast

REF = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
                   "ref/llm-implicit-bias/prompt")

CATEGORIES = {
    "gender": ["career", "power", "science", "sexuality"],
    "race":   ["racism", "weapon", "guilt", "skintone",
               "arab", "asian", "black", "hispanic", "english"],
}
# Folders whose stimuli-CSV 'dataset' key differs from the folder/flag name.
# (arab's implicit script filters =='arab' but the CSV row is 'arab/muslim'.)
CSV_KEY_OVERRIDE = {"arab": "arab/muslim"}


def _fstr(path, var):
    """Return the raw f-string body assigned to `var` (keeps literal \\n)."""
    src = open(path).read()
    m = re.search(rf"{var} = \(\s*f'(.*?)'\)", src, re.S)
    return m.group(1) if m else None


def _list(path, var):
    src = open(path).read()
    m = re.search(rf"^\s*{var} = (\['.*?'\])\s*$", src, re.M)
    return ast.literal_eval(m.group(1)) if m else None


def _literal(path, key):
    """Value of a dict entry like  'group0': 'white',"""
    src = open(path).read()
    m = re.search(rf"'{key}':\s*'([^']*)'", src)
    return m.group(1) if m else None


def build():
    specs = {}
    for cat, folders in CATEGORIES.items():
        for d in folders:
            dec = os.path.join(REF, f"decision/gpt4/{d}/replication.py")
            src = open(dec).read()
            drawn = "pair_group = [random.choice(defaults)" in src

            prompt = _fstr(dec, "prompt")
            prompt = (prompt.replace("{pair_group[0]}", "{g0}")
                            .replace("{pair_group[1]}", "{g1}")
                            .replace("{pair_attribute[0]}", "{a0}")
                            .replace("{pair_attribute[1]}", "{a1}"))

            pos = _list(dec, "positive")   # non-None only when overridden
            neg = _list(dec, "negative")

            # SYNONYM variation (Bai's robustness reword). Only recoverable where the
            # script HARDCODES the two lists: the others read stimuli column 'D', which
            # is absent from the released iat_stimuli.csv, so their synonym stimuli were
            # never published and that arm cannot be reproduced from the artefact.
            syn = os.path.join(REF, f"decision/gpt4/{d}/synonym.py")
            syn_pos = _list(syn, "positive") if os.path.exists(syn) else None
            syn_neg = _list(syn, "negative") if os.path.exists(syn) else None

            sc = os.path.join(REF, f"misc/score/{d}/replication.py")
            p1 = _fstr(sc, "prompt1") if os.path.exists(sc) else None
            p2 = _fstr(sc, "prompt2") if os.path.exists(sc) else None

            specs[d] = {
                "category": cat,
                "csv_dataset": CSV_KEY_OVERRIDE.get(d, d),
                "group_mode": "draw" if drawn else "fixed",
                "fixed_group0": None if drawn else _literal(dec, "group0"),
                "fixed_group1": None if drawn else _literal(dec, "group1"),
                "attr_source": "override" if pos else "c_split",
                "pos_override": pos,
                "neg_override": neg,
                "syn_pos_override": syn_pos,
                "syn_neg_override": syn_neg,
                "decision_prompt": prompt,
                "judge_prompt1": p1,
                "judge_gold": p2,
            }
    return specs


def emit(specs):
    def esc(s):
        return None if s is None else s.encode().decode("unicode_escape")

    lines = ['"""AUTO-GENERATED by gen_specs.py from ref/llm-implicit-bias.',
             'Verbatim Bai prompts + judge few-shots. Do NOT hand-edit; re-run gen_specs.py.',
             '',
             'decision_prompt placeholders: {g0}{g1}{a0}{a1}.',
             'judge_prompt1 placeholders: {stigmas}{negative}; literal {{Decision: {{D}}}}.',
             'group_mode "draw" -> groups drawn from CSV A/B; "fixed" -> fixed_group0/1.',
             'attr_source "c_split" -> C[:h]/C[h:]; "override" -> pos_override/neg_override.',
             '"""', '']
    out = ["CATEGORIES = " + repr(CATEGORIES), "",
           "CSV_KEY_OVERRIDE = " + repr(CSV_KEY_OVERRIDE), "",
           "DECISION_SPECS = {"]
    for d, sp in specs.items():
        out.append(f"    {d!r}: {{")
        for k in ["category", "csv_dataset", "group_mode", "fixed_group0",
                  "fixed_group1", "attr_source", "pos_override", "neg_override",
                  "syn_pos_override", "syn_neg_override"]:
            out.append(f"        {k!r}: {sp[k]!r},")
        for k in ["decision_prompt", "judge_prompt1", "judge_gold"]:
            out.append(f"        {k!r}: {esc(sp[k])!r},")
        out.append("    },")
    out.append("}")
    open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "bai_specs.py"),
         "w").write("\n".join(lines + out) + "\n")


if __name__ == "__main__":
    specs = build()
    emit(specs)
    print(f"wrote bai_specs.py with {len(specs)} datasets")
    for d, sp in specs.items():
        print(f"  {d:9s} [{sp['category']:6s}] mode={sp['group_mode']:5s} "
              f"attr={sp['attr_source']:8s} csv={sp['csv_dataset']:11s} "
              f"judge={'yes' if sp['judge_prompt1'] else 'NO'}")
